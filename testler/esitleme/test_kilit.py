import asyncio, sys, os
from playwright.async_api import async_playwright
ARGS=["--no-sandbox","--host-resolver-rules=MAP mz.test 127.0.0.1","--unsafely-treat-insecure-origin-as-secure=http://mz.test:8123,http://mt.test:8124","--host-resolver-rules=MAP mz.test 127.0.0.1, MAP mt.test 127.0.0.1"]
H=[]
def ok(k,m):
    print(("  ✓ " if k else "  ✗ ")+m)
    if not k: H.append(m)
async def senaryo(br, url, ad, ayarSec, ayarAc, onek):
    print("==", ad)
    ctx=await br.new_context(viewport={"width":1300,"height":860}, service_workers="block")
    await ctx.add_init_script("delete window.showDirectoryPicker;")
    await ctx.clock.install()
    pg=await ctx.new_page(); pg.on("pageerror",lambda e:(print("JS",e),H.append(str(e))))
    pg.on("dialog", lambda d: asyncio.ensure_future(d.accept()))
    await pg.goto(url); await pg.wait_for_timeout(500)
    ok(not await pg.query_selector("#kltPerde"), "şifre yokken kilit yok")
    await ayarAc(pg)
    await pg.click(ayarSec+' [data-klt="koy"]')
    await pg.fill("#kltYeni1","1234"); await pg.fill("#kltYeni2","1234")
    await pg.select_option("#kltSure","5")
    await pg.screenshot(path="ekran-"+onek+"-koy.png")
    await pg.click('[data-klt="kaydet"]'); await pg.wait_for_timeout(800)
    ok(await pg.evaluate("!!(veri.kilit && veri.kilit.h && !JSON.stringify(veri.kilit).includes('1234'))"), "şifre özeti kaydedildi, düz şifre yok")
    await pg.reload(); await pg.wait_for_timeout(600)
    ok(await pg.query_selector("#kltPerde") is not None, "açılışta kilit ekranı geldi")
    vis = await pg.evaluate("!!document.querySelector('main').closest('[inert]')")
    ok(vis, "arkadaki sayfa erişilemez (inert)")
    await pg.screenshot(path="ekran-"+onek+"-kilit.png")
    await pg.fill("#kltSifre","9999"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(900)
    ok("Yanlış" in await pg.inner_text("#kltHata"), "yanlış PIN reddedildi")
    await pg.fill("#kltSifre","1234"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(900)
    ok(not await pg.evaluate("Kilit.kilitliMi()"), "doğru PIN ile açıldı")
    await pg.mouse.move(10,10)
    await ctx.clock.fast_forward("04:00"); await pg.wait_for_timeout(300)
    ok(not await pg.evaluate("Kilit.kilitliMi()"), "4 dakikada kilitlenmedi")
    await ctx.clock.fast_forward("01:30"); await pg.wait_for_timeout(300)
    ok(await pg.evaluate("Kilit.kilitliMi()"), "5 dakika dokunulmayınca kilitlendi")
    # deneme sınırı
    for i in range(5):
        await pg.fill("#kltSifre","0000"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(700)
    ok(await pg.evaluate("document.getElementById('kltSifre').disabled"), "5 yanlıştan sonra bekleme başladı")
    await pg.screenshot(path="ekran-"+onek+"-bekle.png")
    # şifremi unuttum
    await pg.click('[data-klt="unuttum"]')
    kod = await pg.inner_text(".klt-cihazkod"); print("   cihaz kodu:", kod)
    acma = await pg.evaluate("LisansCekirdek.kodUret(LISANS_AYAR.gizli, '%s', veri.kilit.no, 'KILIT')" % kod.split("-")[0])
    await pg.screenshot(path="ekran-"+onek+"-unuttum.png")
    await pg.fill("#kltAcma","111-AAAA-BBBB"); await pg.click('[data-klt="acmaKodu"]'); await pg.wait_for_timeout(200)
    ok("geçersiz" in await pg.inner_text("#kltHata"), "yanlış açma kodu reddedildi")
    await pg.fill("#kltAcma",acma.lower()); await pg.click('[data-klt="acmaKodu"]'); await pg.wait_for_timeout(700)
    ok(not await pg.evaluate("Kilit.kilitliMi()") and await pg.evaluate("!veri.kilit"), "açma koduyla şifre sıfırlandı")
    ok(await pg.query_selector("#kltPencere") is not None, "yeni şifre penceresi açıldı")
    await pg.click('#kltPencere [data-klt="kapat"]')
    await ctx.close()
async def main():
    async with async_playwright() as p:
        br=await p.chromium.launch(executable_path=os.environ.get("CHROME","/usr/bin/google-chrome"),args=ARGS)
        async def mzAc(pg): await pg.click('[data-git="ayarlar"]'); await pg.wait_for_timeout(200)
        async def mtAc(pg): await pg.click('[data-sekme="ayarlar"]'); await pg.wait_for_timeout(200)
        if "mz" in sys.argv: await senaryo(br,"http://mz.test:8123/index.html","MacarZeka","#kltAyar",mzAc,"mz")
        if "mt" in sys.argv: await senaryo(br,"http://mt.test:8124/index.html","Macar Talimat","#kltAyar",mtAc,"mt")
        await br.close()
    print("SONUÇ:", "HEPSİ GEÇTİ" if not H else H)
asyncio.run(main())
